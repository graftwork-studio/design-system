/**
 * Generates the primitive colour palette in DTCG 2025.10 format.
 *
 * Run with `pnpm palette`. The output is committed, so a palette change shows
 * up as a reviewable diff. The brand scale is anchored so that step 500 is
 * exactly the brand colour.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { clampChroma, converter, formatHex, parse, wcagContrast } from "culori";

export const BRAND_HEX = "#2883de";

const toOklch = converter("oklch");
const toRgb = converter("rgb");

const STEPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"] as const;
type Step = (typeof STEPS)[number];

/** OKLCH lightness for each step. Step 500 is replaced by the anchor's own lightness. */
const LIGHTNESS: Record<Step, number> = {
  "50": 0.975,
  "100": 0.945,
  "200": 0.89,
  "300": 0.81,
  "400": 0.72,
  "500": 0.62,
  "600": 0.53,
  "700": 0.46,
  "800": 0.39,
  "900": 0.32,
  "950": 0.25,
};

/** Chroma multiplier per step, so the lightest and darkest steps are calmer. */
const CHROMA_CURVE: Record<Step, number> = {
  "50": 0.12,
  "100": 0.25,
  "200": 0.45,
  "300": 0.7,
  "400": 0.9,
  "500": 1,
  "600": 0.95,
  "700": 0.85,
  "800": 0.72,
  "900": 0.6,
  "950": 0.5,
};

const NEUTRAL_LIGHTNESS: Record<string, number> = {
  "0": 1,
  "50": 0.985,
  "100": 0.967,
  "200": 0.922,
  "300": 0.87,
  "400": 0.708,
  "500": 0.556,
  "600": 0.439,
  "700": 0.371,
  "800": 0.269,
  "850": 0.235,
  "900": 0.205,
  "950": 0.145,
  "1000": 0,
};

type DtcgColor = {
  colorSpace: "srgb";
  components: [number, number, number];
  hex: string;
};

function toDtcg(hex: string): DtcgColor {
  const rgb = toRgb(parse(hex));
  if (!rgb) throw new Error(`Cannot parse ${hex}`);
  const round = (n: number) => Math.round(n * 10000) / 10000;
  return { colorSpace: "srgb", components: [round(rgb.r), round(rgb.g), round(rgb.b)], hex };
}

function hueScale(anchorHex: string, opts: { anchorStep?: Step } = {}): Record<Step, string> {
  const anchor = toOklch(parse(anchorHex));
  if (!anchor) throw new Error(`Cannot parse ${anchorHex}`);
  const peakChroma = anchor.c;
  const hue = anchor.h ?? 0;
  const out = {} as Record<Step, string>;
  for (const step of STEPS) {
    if (opts.anchorStep === step) {
      out[step] = anchorHex.toLowerCase();
      continue;
    }
    const colour = clampChroma(
      { mode: "oklch", l: LIGHTNESS[step], c: peakChroma * CHROMA_CURVE[step], h: hue },
      "oklch",
    );
    out[step] = formatHex(colour);
  }
  return out;
}

function neutralScale(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [step, l] of Object.entries(NEUTRAL_LIGHTNESS)) {
    out[step] = formatHex({ mode: "oklch", l, c: 0, h: 0 });
  }
  return out;
}

export function buildPalette() {
  return {
    brand: hueScale(BRAND_HEX, { anchorStep: "500" }),
    neutral: neutralScale(),
    green: hueScale("#1f9d55"),
    amber: hueScale("#d68a00"),
    red: hueScale("#d93636"),
  };
}

function asTokens(palette: ReturnType<typeof buildPalette>) {
  const color: Record<string, unknown> = {
    $type: "color",
    $description: "Primitive palette. Generated by scripts/generate-palette.ts; do not edit by hand. Apps must not use these directly.",
  };
  for (const [family, scale] of Object.entries(palette)) {
    const group: Record<string, unknown> = {};
    for (const [step, hex] of Object.entries(scale)) {
      group[step] = { $value: toDtcg(hex) };
    }
    color[family] = group;
  }
  return { color };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const palette = buildPalette();
  const target = new URL("../tokens/primitives/color.tokens.json", import.meta.url);
  writeFileSync(target, `${JSON.stringify(asTokens(palette), null, 2)}\n`);

  // A quick reference table to help choose semantic steps.
  for (const [family, scale] of Object.entries(palette)) {
    console.log(`\n${family}`);
    for (const [step, hex] of Object.entries(scale)) {
      const onWhite = wcagContrast(hex, "#ffffff").toFixed(2);
      const onBlack = wcagContrast(hex, "#000000").toFixed(2);
      console.log(`  ${step.padStart(4)}  ${hex}  white ${onWhite.padStart(5)}  black ${onBlack.padStart(5)}`);
    }
  }
}
