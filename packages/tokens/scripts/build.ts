/**
 * Builds the token outputs. The contrast validator runs first and a failure
 * stops the build.
 *
 *   dist/css/tokens.css          CSS variables for every theme
 *   dist/css/tailwind-theme.css  Tailwind v4 theme mapping semantic tokens to utilities
 *   dist/js/tokens.js (+ .d.ts)  JS constants
 *
 * Only semantic tokens are emitted. Primitives are resolved into them and never
 * exposed, so apps cannot reach for a raw palette colour.
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import type { TransformedToken } from "style-dictionary/types";
import { validateAll } from "../src/contrast.ts";
import { CSS_PREFIX, isSemantic, loadTheme, THEMES, type Theme } from "../src/load.ts";

const HEADER = "/* Generated by @graftwork/tokens. Do not edit. */\n";
const dist = new URL("../dist/", import.meta.url);

// 1. Validate. A failing pair fails the build.
const { failures, pairs } = await validateAll();
if (failures.length > 0) {
  console.error(`Contrast validation failed: ${failures.length} problem(s). The build has stopped.\n`);
  for (const f of failures) console.error(`  [${f.theme}] ${f.token} ${f.message}`);
  process.exit(1);
}
console.log(`Contrast validation passed: ${pairs.length} pairs across ${THEMES.length} themes.`);

// 2. Resolve each theme.
const resolved = {} as Record<Theme, TransformedToken[]>;
for (const theme of THEMES) {
  resolved[theme] = (await loadTheme(theme)).filter(isSemantic);
}

const isColour = (t: TransformedToken) => t.$type === "color";
const decl = (t: TransformedToken) => `  --${t.name}: ${t.$value};`;
const colourDecls = (theme: Theme) => resolved[theme].filter(isColour).map(decl).join("\n");
const baseDecls = resolved.light.filter((t) => !isColour(t)).map(decl).join("\n");
const scheme = (theme: Theme) => `  color-scheme: ${theme === "dark" ? "dark" : "light"};`;
const reducedMotion = resolved.light
  .filter((t) => t.path[0] === "motion" && t.path[1] === "duration" && t.path[2] !== "fade")
  .map((t) => `    --${t.name}: 0ms;`)
  .join("\n");

// 3. CSS variables.
const css = `${HEADER}
/* Light is the default. */
:root,
[data-theme="light"] {
${scheme("light")}
${baseDecls}
${colourDecls("light")}
}

/* Follow the operating system unless the user has chosen a theme. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
  ${scheme("dark")}
${colourDecls("dark").replaceAll(/^/gm, "  ")}
  }
}

/* High contrast wins over dark when both are requested. */
@media (prefers-contrast: more) {
  :root:not([data-theme]) {
  ${scheme("high-contrast")}
${colourDecls("high-contrast").replaceAll(/^/gm, "  ")}
  }
}

/* Explicit choices from the theme toggle. */
[data-theme="dark"] {
${scheme("dark")}
${colourDecls("dark")}
}

[data-theme="high-contrast"] {
${scheme("high-contrast")}
${colourDecls("high-contrast")}
}

/* WCAG 2.3.3: no movement under reduced motion. Opacity fades keep their duration. */
@media (prefers-reduced-motion: reduce) {
  :root {
${reducedMotion}
  }
}
`;

// 4. Tailwind v4 theme. Default palettes and scales are cleared so apps can only use ours.
const v = (t: TransformedToken) => `var(--${t.name})`;
const tailwindName = (t: TransformedToken): string | undefined => {
  const [group, ...rest] = t.path;
  const key = rest.join("-");
  switch (group) {
    case "color":
      return `--color-${key}`;
    case "radius":
      return `--radius-${key}`;
    // Named spacing is not mapped: Tailwind would resolve max-w-sm from --spacing-sm.
    // The numeric scale is driven by the space.2xs token instead (see --spacing below).
    case "target":
      return `--spacing-target-${key}`;
    case "breakpoint":
      return `--breakpoint-${key}`;
    case "font": {
      const [kind, ...name] = rest;
      const n = name.join("-");
      if (kind === "family") return `--font-${n}`;
      if (kind === "size") return `--text-${n}`;
      if (kind === "weight") return `--font-weight-${n}`;
      if (kind === "line-height") return `--leading-${n}`;
      return undefined;
    }
    default:
      return undefined;
  }
};
const themeLines = resolved.light
  .map((t) => [tailwindName(t), t] as const)
  .filter((pair): pair is readonly [string, TransformedToken] => pair[0] !== undefined)
  .map(([name, t]) => `  ${name}: ${v(t)};`)
  .join("\n");

const tailwind = `${HEADER}
@theme inline {
  --color-*: initial;
  --radius-*: initial;
  --text-*: initial;
  --font-*: initial;
  --font-weight-*: initial;
  --leading-*: initial;
  --breakpoint-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
  /* Spacing utilities (p-4, gap-2 …) are multiples of the space.2xs token, 0.25rem. */
  --spacing: var(--gw-space-2xs);
${themeLines}
}
`;

// 5. JS constants.
const flat = (theme: Theme) =>
  Object.fromEntries(resolved[theme].map((t) => [t.path.join("."), String(t.$value)]));
const names = resolved.light.map((t) => t.path.join("."));
const js = `${HEADER.replace("/*", "//").replace(" */", "")}
export const themes = ${JSON.stringify(["light", "dark", "high-contrast"])};
export const tokens = ${JSON.stringify(
  { light: flat("light"), dark: flat("dark"), "high-contrast": flat("high-contrast") },
  null,
  2,
)};
/** The CSS custom property for a token path, e.g. cssVar("color.text.default"). */
export function cssVar(path) {
  return \`var(--${CSS_PREFIX}-\${path.replaceAll(".", "-")})\`;
}
`;
const dts = `${HEADER}
export type Theme = "light" | "dark" | "high-contrast";
export type TokenName =
${names.map((n) => `  | ${JSON.stringify(n)}`).join("\n")};
export declare const themes: readonly Theme[];
export declare const tokens: Record<Theme, Record<TokenName, string>>;
export declare function cssVar(path: TokenName): string;
`;

rmSync(dist, { recursive: true, force: true });
mkdirSync(new URL("css/", dist), { recursive: true });
mkdirSync(new URL("js/", dist), { recursive: true });
writeFileSync(new URL("css/tokens.css", dist), css);
writeFileSync(new URL("css/tailwind-theme.css", dist), tailwind);
writeFileSync(new URL("js/tokens.js", dist), js);
writeFileSync(new URL("js/tokens.d.ts", dist), dts);
console.log(`Built ${names.length} semantic tokens into dist/.`);
